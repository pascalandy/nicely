package main

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

func TestLimits(t *testing.T) {
	long := strings.Repeat("word ", 25) + "last.\n"
	large := strings.Repeat("x", 10001)
	cases := []struct {
		name, file, old, new string
		want                 []string
	}{
		{"new size", "new.txt", "", large, []string{"new.txt holds 2501", "more than 2500"}},
		{"size boundary", "small.txt", "", large[:10000], nil},
		{"shrinks", "old.txt", large + "x", large, nil},
		{"grows", "old.txt", large, large + "xxx", []string{"old.txt holds 2501", "grows it by 3 bytes"}},
		{"same size", "old.txt", large, "y" + large[1:], nil},
		{"router", "AGENTS.md", "", strings.Repeat("x", 5001), []string{"AGENTS.md holds 1251", "more than 1250", "AGENTS.md only routes"}},
		{"sum", "tools/go.sum", "", large, nil},
		{"module", "go.mod", "", large, nil},
		{"archive", "docs/archived/x.md", "", long + large, nil},
		{"generated", "generated.go", "", "// Code generated by a tool. DO NOT EDIT.\n\npackage x\n\n// " + long + large, nil},
		{"generated mention", "notes.md", "", "The header `// Code generated by a tool. DO NOT EDIT.` marks a file.\n\n" + long, []string{"notes.md:3", "26 words"}},
		{"generated fence", "notes.md", "", "```go\n// Code generated by a tool. DO NOT EDIT.\n```\n\n" + long, []string{"notes.md:5", "26 words"}},
		{"generated CRLF", "generated.go", "", "// Code generated by a tool. DO NOT EDIT.\r\n\r\npackage x\r\n\r\n// " + long + large, nil},
		{"generated after license", "generated.go", "", strings.Repeat("// License.\n", 12) + "// Code generated by a tool. DO NOT EDIT.\n\npackage x\n\n// " + long + large, nil},
		{"generated without package", "manual.go", "", "// Code generated by a tool. DO NOT EDIT.\nThis is ordinary text.\n// " + long + large, []string{"more than 2500", "manual.go:3", "26 words"}},
		{"generated after package", "manual.go", "", "package x\n\n// Code generated by a tool. DO NOT EDIT.\n\n// " + long + large, []string{"more than 2500", "manual.go:5", "26 words"}},
		{"generated in a string", "manual.go", "", "package x\n\nconst marker = `\n// Code generated by a tool. DO NOT EDIT.\n`\n\n// " + long + large, []string{"more than 2500", "manual.go:7", "26 words"}},
		{"catalog", "internal/x/locales/en.toml", "", large, nil},
		{"binary", "binary.md", "", "\x00" + long + large, nil},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			before := map[string]string{}
			if tc.old != "" {
				before[tc.file] = tc.old
			}
			root := limitsRepository(t, before)
			write(t, filepath.Join(root, filepath.FromSlash(tc.file)), tc.new)
			limitsTestGit(t, root, "add", ".")
			assertLimits(t, root, tc.want)
		})
	}
}

func limitsRepository(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	limitsTestGit(t, root, "-c", "init.templateDir=", "init", "-q")
	limitsTestGit(t, root, "config", "user.name", "Test")
	limitsTestGit(t, root, "config", "user.email", "test@example.com")
	limitsTestGit(t, root, "config", "commit.gpgsign", "false")
	limitsTestGit(t, root, "config", "core.hooksPath", "/dev/null")
	for name, text := range files {
		write(t, filepath.Join(root, filepath.FromSlash(name)), text)
	}
	limitsTestGit(t, root, "add", ".")
	limitsTestGit(t, root, "commit", "--allow-empty", "-qm", "Base")
	return root
}

func limitsTestGit(t *testing.T, root string, args ...string) {
	t.Helper()
	cmd := exec.Command("git", append([]string{"-C", root}, args...)...)
	cmd.Env = os.Environ()
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git %v: %v\n%s", args, err, out)
	}
}

func assertLimits(t *testing.T, root string, want []string, args ...string) {
	t.Helper()
	var out strings.Builder
	err := run(append([]string{"limits", root}, args...), &out)
	if (err != nil) != (len(want) > 0) {
		t.Fatalf("limits error = %v, want %v; output: %s", err, want, &out)
	}
	if err == nil {
		if out.Len() != 0 {
			t.Fatalf("success printed %q", out.String())
		}
		return
	}
	text := out.String() + err.Error()
	for _, part := range want {
		if !strings.Contains(text, part) {
			t.Errorf("limits lacks %q:\n%s", part, text)
		}
	}
	for _, prefix := range []string{"Split each file", "Rewrite each sentence", "AGENTS.md only routes"} {
		if strings.Count(text, prefix) > 1 {
			t.Errorf("limits repeats %q:\n%s", prefix, text)
		}
	}
}
